package cn.dsr213.hyperplus

import android.content.Context

/**
 * 引擎侧「给用户看的一句话」—— 按系统语言在中／繁／英里选一条。
 *
 * ============================ 为什么引擎里要有一份"文案表" ============================
 * 这与「引擎刻意不本地化」**不矛盾**，两者管的是不同的东西：
 * - 「不本地化」管的是**日志**（看日志的是我和用户，双语反而难 grep）；
 * - 这里管的是**给用户看的浮层 / Toast**，它与 App 那三套 `strings.xml`
 *   是**同一件事的两处落点** ⇒ 措辞必须与 App 侧**完全一致**（逐字）。
 *
 * ============================ 为什么集中在这一个文件 ============================
 * ★ 本对象的前身是 `SplitTrigger` 里的一个 private `pickText` —— 2026-10-05 因为
 *   「旋转失败」这句提示需要**第二处**调用，才把它提出来。
 *   ⛔ **绝不要为了"省一次跳转"在别处再写一份判语言的 `when`** ——
 *      抄两遍就会有一天只改对一处（这正是原注释里那条纪律，搬过来时一并保留）。
 *
 * ⚠️ **判据只认语言标签前缀**，不比 `Locale` 对象：引擎进程里的 `Configuration`
 *   可能被 SystemUI 自己的覆盖行为影响，按**字符串前缀**判最稳（也最好读）。
 * ⚠️ 认不出就落到**英文** —— 与 App 四档的兜底一致（其它语言 ⇒ 英文）。
 * ⛔ 别为此引一套资源读取：引擎进程读本模块 APK 的资源要走额外的 context 包装
 *   （见 `module/HostEnv`），为几个短句不值得。
 *
 * ============================ 文案纪律（逐条都有出处，别顺手"优化"）============================
 * - 中文一律是**用户原话或用户点名要的说法** ⇒ ⛔ 不许改写措辞；
 * - 用户看得懂的是**他要做的动作**，⛔ 不用内部术语（「补齐」「补格」那类）；
 * - 界面文案里 ⛔ 不许写 markdown（星号会原样显示），强调一律用「」。
 */
internal object EngineText {

    /**
     * 三语选一（zh 简体 / zh-Hant 繁体 / 其它 ⇒ 英文）。
     *
     * ★ 抽出来的理由见类注释：这条判据**全工程只允许有一份**。
     */
    fun pick(host: Context, zh: String, zhHant: String, en: String): String {
        val tag = runCatching {
            host.resources.configuration.locales[0].toLanguageTag()
        }.getOrDefault("")
        return when {
            tag.startsWith("zh-Hant") || tag.startsWith("zh-TW") || tag.startsWith("zh-HK") ||
                tag.startsWith("zh-MO") -> zhHant
            tag.startsWith("zh") -> zh
            else -> en
        }
    }

    /**
     * 半自动写了方向、**两次读回屏幕都没动** ⇒ 告诉用户这次旋转没成功。
     *
     * ⚠️ 中文是**用户 2026-10-05 点名要的说法**（原话：「转不动就弹 toast 提示 旋转失败」）
     *   ⇒ ⛔ 不许顺手"优化"成「这个应用不支持旋转」之类的解释性措辞。
     *
     * ★ 为什么由**引擎**弹（而不是 App）：这一刻用户正看着**别的应用**（他是在那个应用里
     *   点了悬浮按钮），而 Android 10+ 起后台普通应用弹 Toast 会被系统**静默丢弃**
     *   （见 [AppToast] ① 的实测）。引擎跑在 SystemUI 系统进程里 ⇒ 不受那条限制。
     *
     * ★ 与它配对的那个**旧行为已删除**（2026-10-05 用户点名）：原来这一支会把这个
     *   「包 + 形态」**记进名单、此后永久静默停手**（`Uncontrollable`，A 方案）。
     *   现在改成"只提示这一次"—— 不落盘、不改变后续行为。
     *   ⇒ 所以这句提示**必须能重复出现**（用户再点、再失败，就该再看到），
     *     不能像旧机制那样"提示过就不再提示"。去重只由 [AppToast] 那 2 秒负责。
     */
    fun rotationFailed(host: Context): String =
        pick(host, "旋转失败", "旋轉失敗", "Rotation failed")
}
