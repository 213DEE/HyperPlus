/**
 * 一次 burst 采多少帧。
 *
 * ★ 16 → 10 → **8**（2026-09-25，用户反馈"把 12 票改成 6 票、响应太慢"）。
 *
 *   ⚠️ **先厘清用户说的"12 票"是哪个数**（这一步不能跳）：         *     用户是在 HUD 上看到 **有效票数**（`voteValid`，形如 `投票[0:3 1:9] 有效票 12`），
 *     那不是投票**门槛**（门槛是 [MIN_VOTES]），而是**本轮真正采到的票数** ——
 *     它 = [BURST_FRAMES] − 预热帧 − 没脸的帧。所以要让"12 → 6"真的成立，
 *     该动的是**这里**（采多少帧），不是把门槛从 6 砍半。
 *
 *   旧值 16 是按"EMA(α=0.35) 收敛需 7 帧 + holdMs 确认期 4 帧"算的，
 *   但那条算式**只在"靠状态机收尾"时成立** —— 现在每帧都投票、
 *   票一够就落定（见 [VOTE_WARMUP_FRAMES] / [MIN_VOTES]），
 *   根本不需要等状态机收敛。
 *
 *   8 帧 − 预热 2 帧 = **6 票**，正是用户要的数字；8 帧 ≈ 0.27s（30fps），
 *   比 16 帧的 ~0.53s 快一倍。⚠️ 更短的 burst 还有两个副作用，都往好处走：
 *    ① `finishBurst` 更早 ⇒ [recentConsensus] 那条"转 180° 兜底"也更快落地；
 *    ② 相机**占用时间变短** ⇒ 与 `com.miui.aoc` 抢 Device 0/1 的窗口变小，
 *       "一帧都没给"的冲突概率随之下降（这是"反转 180° 画面没反应"的另一半原因）。
 */
const val BURST_FRAMES = 8

/**
 * 「会话已死」的判定阈值：这么久（ms）没收到任何帧 ⇒ 认为相机会话已被系统踢掉。
 *
 * ★ 依据（2026-09-25 真机日志 + `dumpsys media.camera` 双重实证）：
 *   `com.miui.aoc`（小米 AON）会 `Evicted by device 0 client for package com.miui.aoc`
 *   把我们的前摄会话异步踢掉，且**不产生任何回调** —— 唯一的事实是 `analyzer 总帧` 冻结。
 *
 * 取 1000ms 的理由：
 *  - 会话活着时帧是连续的（640×480 分析流 ~30fps ⇒ 每帧 ~33ms），1000ms ≈ 30 个帧周期，
 *    偶发卡顿**不可能**连续 30 帧不来 ⇒ 几乎不会误杀；
 *  - 又明显小于 [BURST_TIMEOUT_MS]=1500ms ⇒ 能在超时之前就识别出来，
 *    把那段"干等"真的省掉（用户感知就是"转了立刻有反应"，而不是卡一下）。
 */
const val SESSION_STALE_MS = 1000L

/** burst 硬超时：超过这个时间还没凑齐帧数就放弃，防止僵尸 burst 把状态机卡死 */
const val BURST_TIMEOUT_MS = 1500L

// ---------------------------------------------------------- 前摄 id 轮换
//
// ★ 为什么需要（2026-09-25，用户报"卡住了，换一个前摄id吧"）：
//   本机有 5 个前摄（`1,5,7,8,9`），旧代码写死 `DEFAULT_FRONT_CAMERA`（id "1"）
//   ⇒ 一旦 id "1" 拿不到，引擎就只能反复重试同一个 id，**没有第二条路**。
//
//   换 id 的物理依据来自各设备的 `Conflicting devices:`（工具读自 dumpsys）：
//     1 → {8,7}   7 → {8,1}   8 → {7,1}     ← A 组，三者互斥
//     5 → {9}     9 → {5}                   ← B 组，两者互斥
//   两组**没有任何交叉** ⇒ A 组被占时 B 组仍可开。且 5 个前摄的 `Orientation`
//   全是 270 ⇒ 换 id 不会改变 roll 的固定基准（方向映射不受影响）。

/**
 * 同一个 id 连续失败几次才换下一个。
 *
 * 取 1：**一轮 burst 收到 0 帧是硬事实** —— 这个 id 此刻就是拿不到。
 * 再等一轮只会白烧 [BURST_TIMEOUT_MS]（1.5s），用户看到的就是"又卡了一下"。
 * 换 id 的代价只是重新 bind（几十毫秒），比干等便宜得多。
 */
const val FRONT_FAIL_TO_ROTATE = 1

/**
 * 允许换满几圈。取 1 —— 5 个前摄各试一次已经把所有选择用尽；
 * 立刻从头再试一遍没有意义（挡住我们的条件并没有变化）。
 * 试完就暂停，交给「让位 + 等它松手补采」那条更省的路。
 */
const val FRONT_MAX_CYCLES = 1

/** 换满一圈后暂停轮换多久（ms）—— 期间只让位等待，不再盲试 */
const val FRONT_ROTATE_PAUSE_MS = 6000L

/**
 * 「被别人占着」这个判定的保质期（ms）。
 *
 * ★ 依据（真机日志）：`com.miui.aoc` 11:19:40 已经 `DISCONNECT + DIED`，
 *   我们 11:19:44 / 11:19:49 还在打"让步：相机在别人手里" —— 标志位卡死了。
 *   成因是它只靠 AvailabilityCallback 的**跳变**更新，而跳变可能被
 *   `selfHolding` 挡板吃掉；一旦错过就再也没有下一次跳变。
 *
 * 取 1500ms：aoc 的占用窗口实测是秒级（那次 5s），但"多试一次"的代价只是
 * bind 失败（几十~几百毫秒），而"误判被占"的代价是**用户完全没反应** ——
 * 两侧代价不对称，所以宁可偏乐观、早点放行试探。
 */
const val OCCUPANCY_STALE_MS = 1500L

/**
 * 前台门控的巡检周期。
 *
 * ★ 取 2 秒的理由：门控要解决的是"游戏期间引擎别抢 CPU/GPU"，而用户切进/切出游戏
 *   **不会产生传感器触发** —— 复检太慢（比如 10 秒）会让常驻相机白开很久；
 *   太快（<1 秒）则 IPC 频率白涨。2 秒正好卡在"及时"与"省"之间。
 * ⚠️ 循环里在确认该干活之前**一次 IPC 都不发**（见 [startForegroundWatch]），
 *   所以这个周期只在 ADAPTIVE 且触发层在跑时才真的产生开销。
 */
const val FOREGROUND_POLL_MS = 2000L

/**
 * 「形态（内/外屏）配置变了、等折叠动画落定后再量一次」的延时。
 *
 * ★ 为什么需要第二次：折叠屏展开/收拢是**带过渡动画**的，`onConfigurationChanged`
 *   回调触发的那一刻尺寸可能还在中间态 —— 本机内屏 1672×2364、外屏 1168×1712，
 *   中间态既不是这个也不是那个，只量一次会把模式档位判到错误的那块屏上。
 *   300ms 是折叠动画的量级。
 * ⚠️ 幂等：形态没变时 `AppPrefs.syncScreenForm` 只做一次比较，不产生任何副作用。
 */
const val FORM_SETTLE_MS = 300L

/**
 * HyperOS **每块屏各自的方向槽位**键前缀 —— 拼上 [ScreenForm.storageKey] 就是
 * `user_rotation_inner` / `user_rotation_outer`。
 *
 * ★★★ 2026-10-02 找到「每次展开都要自己转一下」的**总病根**：本机的方向不是一份，是**三份**——
 *   · `user_rotation`（AOSP 标准键，**全局只有一份**）—— v4～v7 一直在读写它；
 *   · `user_rotation_inner` / `user_rotation_outer`（**HyperOS 私有，每屏一份**）。
 *   而框架**展开/折叠时拿的是后者**。实测证据（01:30 那一轮）：
 *   · `settings get system user_rotation_inner` = **2**、`_outer` = **0**；
 *    `dumpsys window` 里 `mUserRotationInner=ROTATION_180`、`mUserRotationOuter=ROTATION_0`
 *    —— 与两个键**一一对应**；
 *   · `settings put system user_rotation_inner 3` ⇒ `mUserRotationInner` **立刻**由
 *    `ROTATION_180` 变 `ROTATION_270` ⇒ 这个键**有 observer 直连 WMS**，写了就生效。
 *
 * ⇒ 病根不是"改得不够早"，而是**改错了键**：我们每次改全局键，槽位却从没被碰过，
 *   于是每次展开框架照灌旧槽位（2 = 竖屏），我们再改一次全局键 —— 用户就**每次都看到
 *   "自己转一下"**（这正是他的原话）。
 *
 * ★ 现在的策略：**把定方向的权利交回用户** —— 界面上「默认方向」让用户直接指定
 *   这块屏该是哪个方向（App 借 root 直写，见 [cn.dsr213.hyperplus.RootShell]）。
 *   于是展开时框架**自己**就把正确的值灌进去了 ⇒ 我们零写入、用户零旋转，
 *   这才是用户要的「一展开就是屏幕正对我，而不是自己转一下」。
 *   ⛔ 模块**不再自动写这个键**（2026-10-02 那版"写全局键时顺手同步槽位"已在 10-03
 *     删除）：那会把用户刚定下的值覆盖成"当前方向"，又变成"设置了却不生效"。
 *   ⚠️ 2026-10-03：曾经还有一次"延迟 800ms 复核方向"的兜底，**已随「展开默认方向」
 *   功能整体删除** ⇒ 现在没有任何事后纠正：槽位是什么，展开就是什么。
 */
const val KEY_USER_ROTATION_PREFIX = PrefsBridge.KEY_USER_ROTATION_PREFIX

/**
 * 换屏搬运之后的**看护窗**：复查间隔 × 次数（≈ 3.1 秒）。
 *
 * ★★ 为什么从"校验 2 轮"改成"看护一整段"（2026-09-29 第三次修，用户原话
 *   「展开的时候是正确方向，然后才跳到错误的方向」）：
 *   旧写法一旦发现**已对齐就立刻 `return`** —— 于是"对齐"之后发生的覆盖，
 *   我们**一次也看不见**。而用户看到的正是这个顺序：先对（我们的搬运生效了），
 *   后错（随后又被别人盖掉）。
 *
 * ✅ 现场机制已查明（`dumpsys window displays` 直读）：
 *   ```
 *   mUserRotationModeInner=USER_ROTATION_LOCKED  mUserRotationInner=ROTATION_270   ← 内屏槽位 = 3（陈旧）
 *   mUserRotationModeOuter=USER_ROTATION_LOCKED  mUserRotationOuter=ROTATION_0
 *   ```
 *   HyperOS 给**每块屏**存了一份方向记忆（AOSP 没有）。我们把面板值写进
 *   `USER_ROTATION` 时，只更新了**当前活动屏**那份；另一块屏的槽位**原封不动**。
 *   展开时框架把目标屏槽位那个**陈旧值**灌进 `USER_ROTATION` —— 它可能落在我们之后
 *   ⇒ 屏幕上就是"先对、后跳错"。
 *
 * ⇒ 现在改成**看护窗**：每 [HANDOFF_WATCH_STEP_MS] 复查一次，只要整段窗口内
 *   方向被改掉就**改回来**（写绝对值、幂等，不会像 `+2` 那样翻回去）。
 *   每次开窗都只认"我这次写下去的值"，且**一律重过"别抢用户方向盘"的闸**
 *   （`lastWriteAt` 变了 = 用户点了按钮 / 切了模式；方向盘不在手里；前台门停手）
 *   ⇒ 窗口再长也**不会**跟用户较劲。
 *
 * ⚠️ 3.1 秒的由来：折叠动画 + 显示重配的量级在这个区间内；再长就有"抢用户方向盘"
 *   的嫌疑（用户在这段时间里点按钮会被 `lastWriteAt` 闸放行，不受影响）。
 */
const val HANDOFF_WATCH_STEP_MS = 350L
const val HANDOFF_WATCH_CHECKS = 9

/**
 * 换屏后、读"当前握姿"之前要等的时长（ms）。
 *
 * ★★ 为什么必须等（2026-09-30 的真机现场）：用户**合着看外屏时是竖持**，
 *   展开时手才转成**横持** —— 所以 `onScreenFormChanged` 被回调的那一瞬间，
 *   传感器手上还是**外屏时期的旧姿态**。此时若立刻按姿态定方向，算出来就是
 *   "竖屏"，正好等于我们要修的那个 bug。
 *
 * 🔎 实测（`lhasa`，00:56:02 那次展开）：回调后 60ms 重力读数已换成新姿态
 *   （`ax=-8.71`，横持）。取 250ms 是留足余量，代价是屏幕上"旧方向"多停留
 *   0.25 秒 —— 换屏本身有折叠动画，用户感知不到。
 *
 * ⚠️ 这个等待**必须在协程里**（[onScreenFormChanged] 整段已搬进 `scope.launch`），
 *   而且要连带"期间有人写过就不抢方向盘"的闸（见那里的 `entryWriteAt`）。
 */
const val HANDOFF_POSTURE_SETTLE_MS = 250L

// ---------------------------------------------------------- 半自动模式（2026-09-28）

/**
 * 半自动：弹过按钮之后的最短间隔（ms）。
 *
 * ★ 500ms（2026-09-28 用户报"转完之后马上再转，就没有按钮了"后从 1500ms 降下来）。
 *   它只需要挡住"一次转动跨的多个采样点"，而触发层自己的去抖已经是
 *   `minTriggerIntervalMs=300` / `minGyroIntervalMs=400` —— 两者相加，
 *   任何真实的"两次转动"都隔得比 500ms 远。
 *
 * ★ 而且这个冷却**不含任何惩罚性**：[RotateHintOverlay.show] 对"已在显示"
 *   是原地换目标 + 重置倒计时，所以冷却偏短只会让按钮更跟手，不会更烦。
 */
const val SEMI_COOLDOWN_MS = 500L

/**
 * 半自动：**姿态稳定确认窗口**（ms）—— 触发之后等这么久，期间没有新触发才真的弹。
 *
 * ★ 为什么需要（2026-09-29，用户报「转 180° 时 90° 弹一次、180° 又弹一次」）：
 *   转 180° 的过程中重力扇区会**依次**经过 0 → 1 → 2。停在 90° 那一刻姿态合法、
 *   又与当时的屏幕方向不同 ⇒ 先弹一次；停到 180° 再弹一次。
 *   两道已有闸都跨不过中间这一步：[SEMI_COOLDOWN_MS] 只有 500ms，
 *   而重复抑制要求"同一目标方向"（90° 与 180° 是两个不同目标）。
 * ★ 这是一个 **debounce**：窗口内每来一个新触发就把时间往后推 ——
 *   转动过程中一次都不弹，姿态真停住了才弹一次。
 *
 * 【取值判据（下次要调它先看这里）】
 *  - 它只需要盖过"**经过** 90° 的那一小段"，不是整次转动（因为会被反复重置）——
 *    真正的"防手抖"在触发层（`minTriggerIntervalMs` / `GYRO_RATE_DPS`）。
 *  - 太小（< 150ms）⇒ 快速甩动时 90° 那一帧仍会被抓成一次弹出；
 *  - 太大（> 500ms）⇒ 用户会觉得"转完了按钮半天不出来"，
 *    而这正是 2026-09-25~28 那两轮反复投诉过的"不够跟手"。
 *  - 280ms 落在两者之间：约等于"手明显停住"的判读下限，且比一次显示重配（250~400ms）还短。
 */
const val SEMI_SETTLE_MS = 280L

/**
 * 半自动：写完方向后**读回屏幕真实旋转**的等待时长（ms）。
 *
 * ★ 取值依据：写 `Settings.System.USER_ROTATION` 到屏幕真转过去，中间隔着一次
 *   **显示重配**（WMS 重算配置 + 旋转动画），量级 250~400ms ⇒ 600ms 留了余量。
 * ★ 判据是"宁可多等、不可误判"：读早了会把**明明转成功**的场景报成失败，
 *   弹一句没来由的「旋转失败」⇒ 用户从此不再信这句提示，比多等半秒严重得多
 *   （理由见 [scheduleSemiReadback]）。
 * ⚠️ 它是**两段**等待（两次读回之间也隔这么久）⇒ 判定最坏在点击后约 1.2 秒完成。
 *   这段时间里按钮早已收起，用户感知不到这个延迟。
 */
const val SEMI_READBACK_MS = 600L

/**
 * 半自动：用户**点击**之后的间隔（ms）。
 *
 * ★★ 这是用户那句「转完之后马上再转、就没有按钮了，一定要隔一会再按」的**根因**，
 *   原值 4000ms 属于过度保护（2026-09-28 降到 700ms）。
 *
 * 曾经的顾虑是：写 `user_rotation` 之后系统要做一次显示重配（几百 ms），
 * 重配过程本身又会产生新的传感器事件，沿用短冷却会让按钮在"屏幕还在转"时又弹出来。
 * 这个顾虑本身成立，但 **4 秒是拿错了刻度** —— 一次显示重配的动画量级是
 * 250~400ms，700ms 已经把它完整盖住，而多出来的 3.3 秒纯粹是在拦用户。
 *
 * ★ 判据（下次要调这个值前先看这里）：
 *   "屏幕还在转时就弹" ⇒ 这个值**太小**；
 *   "点了之后马上想转另一个方向却弹不出来" ⇒ 这个值**太大**。
 *   用户实测的是后者，所以往下调。
 */
const val SEMI_TAP_COOLDOWN_MS = 700L


/** 标定采样窗口：主动开相机采这么久，再取中位数 */
const val CALIBRATION_MS = 2600L

/** 标定至少要有这么多个有效人脸样本才算成功 */
const val MIN_CALIB_SAMPLES = 5

/**
 * 两次写入 `user_rotation` 之间的最小间隔 —— 等系统把新方向反映到 display 上。
 *
 * ★ 300 → **120**（2026-09-25，响应提速）：旧值是为了防"同一帧里连写 3 次"
 *   （系统回读有几十~几百 ms 延迟）。但那道闸真正要挡的是**重复写同一个值**，
 *   而 [applyRotationIfNeeded] 已经先用 `displayRotation() == s.rotation` 挡掉了。
 *   120ms 足够覆盖一次 Settings 写入 + 回读，又不会把"连续两次真实转向"压掉。
 */
const val WRITE_COOLDOWN_MS = 120L

/**
 * 「相机保温期」：省电优先下，上一轮 burst 结束后相机还留多久。
 *
 * ★ 为什么要（2026-09-25，用户反馈"响应太慢、不够灵敏"）：真机日志显示
 *   当前策略是**省电优先**（`hyperplus_capture_strategy=POWER_SAVING`），
 *   而旧行为是"burst 一结束就 unbind"。于是**每一次触发**都要重新开流 ——
 *   实测 `openMs≈222ms`，这 222ms 里一帧都没有。用户连续摆姿势时，
 *   这部分开销被人为地付了 N 遍，正是"慢"的主体。
 *
 * ★ 3000 → **8000**（2026-09-28，用户报「延迟大 / 不跟手」）：
 *
 *   3 秒是按"连续操作时相邻两次触发相隔 0.5~2s"估的，但它漏了一种很常见的节奏 ——
 *   用户转一下 → 看一眼屏幕 → 不满意、再转一下。这个间隔**经常超过 3 秒**，
 *   于是每一轮都要重新付一次 `openMs`（实测 ≈222ms，这段时间一帧都没有）。
 *   而"延迟大"正是本轮用户点名的两个问题之一。
 *
 *   8 秒把"想一下再转"这个节奏也包进来了。代价是用户真正放下手机后相机会
 *   多留 5 秒 —— 相比切到"响应优先"（**永久**常驻开流）仍然温和得多，
 *   而且**电量只在"正在用"的时段付**（每次收尾都会重置计时，停了才关）。
 */
const val CAMERA_KEEP_WARM_MS = 8000L

/** 相机绑定失败后的重试延迟（首次失败多是上一个 burst 未收尾，不是真被占用） */
const val BIND_RETRY_DELAY_MS = 400L

/**
 * 一次触发允许的**补试**次数（见 [scheduleRetry]）。
 *
 * ★ 为什么必须有：触发是"设备动了才来"的事件。如果那一次 burst 因为相机
 *   一帧都没给而放弃（实测：被 `com.miui.aoc` 这类系统服务抢走），
 *   用户已经转到新姿势了，**不会再有第二次触发** —— 屏幕就永远停在上一次的方向，
 *   表现正是"转了手机没反应"。补试把这个洞堵上。
 *   取 2 是为了在"抢走会自己松开"与"别把电池烧掉"之间折中。
 */
const val MAX_BURST_RETRY = 2

/** 补试延迟：给抢走相机的那一方一点释放时间，又不至于让用户觉得卡 */
const val RETRY_DELAY_MS = 700L

/**
 * 「多帧投票」定论所需的最少票数。
 *
 * ★ 6 → **3**（2026-09-25，用户反馈"响应时间太慢、不够灵敏"，并提到
 *   "手机都反转 180 度了画面还没反应"）。改动的**前提**是这一轮同时做了两件事：
 *   ① [BURST_FRAMES] 16 → 8、[VOTE_WARMUP_FRAMES] 4 → 2（整轮变短，实采 6 票）；
 *   ② 每帧都尝试落定（[applyRotationIfNeeded] 只认票）—— 票一到就写，
 *      不必等状态机收敛。
 *   于是 3 票 ≈ 开流后 100ms 即可定论，比旧的 6 票（≈350ms）快一倍多。
 *
 * ⚠️ **3 会不会太松？看这一条就安心**：[VoteTally] 定论要求"票数 ≥ [MIN_VOTES]
 *   **且**占比 ≥ [VOTE_RATIO_MIN]=60%（或 2 倍领先）"。6 票的盘子里要 60% 就是**至少 4 票**，
 *   所以 [MIN_VOTES]=3 只在"总票数 ≤ 5"（脸丢得多）时才真正起作用 ——
 *   它放宽的是**样本稀少时也敢下结论**，不是"两票就转"。
 *
 * ⚠️ 6 票的旧理由（"门槛 4 时会早采纳再纠正"）在此依然成立，只是**成因已被拆掉**：
 *   当时的 4~5 帧多数落在错的一侧，是因为那几帧拍的是**转动前的旧姿势**
 *   （见 [VOTE_WARMUP_FRAMES] 的真机证据）。预热帧 + EMA 已经把那批坏帧挡在外面，
 *   所以现在降低门槛不会把老毛病带回来。
 *
 * ⚠️ **风险与底线**：3 票是"三帧一致"才成立（还要求占比 ≥ 60% 或 2 倍领先，
 *   见 [VOTE_RATIO_MIN]）；若真机又出现"先跳一下再跳回来"，第一个该回调的就是这里。
 *   低于 [MIN_VOTES] 时**不许下结论**，退回 [OrientationDecider.settle]。
 */
const val MIN_VOTES = 3

/** 绝对多数阈值：获胜方占比到这个数就算定论 */
const val VOTE_RATIO_MIN = 0.6f

/**
 * 「末段共识」看最后几票（见 [recentConsensus]）。
 *
 * 取 3 的理由：与 [MIN_VOTES] 同量级 —— 末段兜底给出的结论，可信度标准不该比
 * 整轮定论更低。太小（2）会被单帧噪声骗，太大（5~6）就退化成"整轮多数"了，
 * 治不了"转 180° 被过渡姿势切散"那个病。
 */
const val RECENT_VOTES = 3

/**
 * 投票的**预热帧数**：一轮 burst 的前这么多帧不计票。
 *
 * ★ 依据（2026-09-25 真机日志，实证）：
 *   burst 是**被"设备动了"触发**的，而相机开流要 ~220ms（实测 openMs=222）。
 *   所以开头几帧拍到的常常是**还没转完的旧姿势**。日志证据：某轮票面
 *   `0:4 1:9 3:3`，而**上一轮刚把方向写成 0**，那 4 张 "0" 票就是转动前的残留。
 *   它们会把多数往旧方向拉 —— 这正是"竖屏切回横屏有概率切反"的一个来源。
 *
 * ★ 4 → **2**（2026-09-25，响应提速）：预热的本质是"甩掉开流瞬间的旧姿势"，
 *   而相机的开流等待已经体现在 `openMs`（bind → 首帧）里，**首帧本身就已经是新姿势了**；
 *   真正需要甩掉的是紧随其后的 1~2 帧（自动曝光/自动对焦还没稳）。
 *   取 2 后 8 帧里仍有 6 帧可投 —— 这正是用户要的"6 票"，
 *   也是 [MIN_VOTES]=3 的两倍。
 */
const val VOTE_WARMUP_FRAMES = 2

/**
 * 允许"退回状态机结果"落盘所需的最少帧数（burst 收尾时判）。
 *
 * ★ 为什么要有：被系统常开相机抢走 / 中途被打断的 burst 帧数很少，
 *   此时 [OrientationDecider.settle] 给出的可能只是"开头那几帧的旧方向"。
 *   **宁可不判，也不能拿残帧写屏幕** —— 屏幕留在原方向，等下一次触发重来。
 *   （随 [BURST_FRAMES] 从 16 → 10 → 8，这里也从 8 → 6 → 5，
 *   始终留出"允许丢 3 帧"的余量，避免相机稍有抖动就整轮作废。）
 */
const val MIN_FRAMES_FOR_SETTLE = 5

/**
 * 判定"手机是否完全平放"的平面重力分量阈值（m/s²）。
 *
 * 低于它就认为重力几乎全落在 z 轴、平面内算不出可信方向 ⇒ [gravitySectorNow] 返回 null、
 * 退回人脸单源。取 1.5 而不是更大的值，是因为**斜拿着看视频**（俯仰 70°）时
 * 平面分量仍有 `g·cos70° ≈ 3.4` —— 阈值定高了会把正常姿势误判成平放。
 */
const val GRAVITY_MIN_PLANAR_G = 1.5f

/**
 * 判定"符号位该不该翻转"所需的最少**分辨帧**数（见 [noteSignEvidence]）。
 *
 * 为什么取 20 而不是 5：符号位是**全局性**的一位 —— 它错了整片横屏反向，
 * 它被误翻一次同样是整片横屏反向。而"分辨帧"每轮 burst 最多产生 1 个，
 * 所以 20 帧 ≈ 正常用机 1~2 分钟，代价可以接受。
 * 另一半判据「反号证据 ≥ 3 倍正号证据」在 [OrientationFusion.shouldFlip] 里。
 */
const val SIGN_MIN_SAMPLES = 20

// ---------------------------------------------------------- 启动熔断（2026-10-03）

/**
 * 启动熔断阈值：启动前读到"连续失败次数"**达到这个数**，就不再自动启动引擎。
 *
 * ★★ 为什么要有它（2026-10-03 两名用户反馈「装完模块后崩溃 / 系统界面反复重启」）：
 *   引擎住在 SystemUI 进程里，而"一次异常就停用"的那个开关（`EngineHost.dead`）
 *   **只活在内存里** —— SystemUI 一重启它就复位。于是**确定性故障 = 精确的无限循环**：
 *   每次 SystemUI 起来 → 4 秒后引擎启动 → 触发故障 → 进程死 → 再来一遍。
 *   用户既进不了桌面，也没有任何界面入口能关掉它。
 *
 * ★ 取 3 的理由 —— 它直接决定"用户要忍受几次重启"：
 *   - 1 或 2：单次偶发（比如开机时相机被别的服务占着导致的一过性失败）就会被误判成熔断，
 *     而且熔断后功能**静默消失**，用户只会觉得"模块莫名坏了"；
 *   - 3 ⇒ 最多重启 **2 次**就停手，代价可接受，误判概率又足够低；
 *   - 更大（4+）：用户要等 3 次以上黑屏，与"让系统尽快停下来"的目标相悖。
 *
 * ⚠️ 计数口径是**保守**的：它只问"这次 SystemUI 启动后有没有活过 [BOOT_HEALTHY_WINDOW_MS]",
 *   不问死因。所以"用户在 60 秒内手动重启两次系统界面"也会累积 2 次 ——
 *   这是**刻意**的取舍：宁可偶尔误停（App 里有「重新启用」，一下就能恢复），
 *   也不要漏掉真故障（漏掉的代价是无限重启）。
 */
const val BOOT_BREAKER_THRESHOLD = 3

/**
 * 健康运行窗：引擎启动之后**连着活过这么久**，就把启动计数清零。
 *
 * ★ 取值依据：真机上引擎的启动序列是"SystemUI 起来 → +4 秒跑 `doBoot` →
 *   加载 8.5MB native 库 / 初始化 ML Kit / CameraX → 若干秒内见分晓"。
 *   60 秒远大于这条序列，不会把"只是慢"误判成失败。
 *
 * ⚠️ 它与 [BOOT_BREAKER_THRESHOLD] 的关系是"**凑满 N 次失败的窗口内重启**
 *   才熔断"：正常用机（系统界面长期不重启）计数永远是 0。
 *   ⇒ 实测口径（2026-10-03 定稿）：**确定性故障最多让系统界面重启 2 次就停。**
 */
const val BOOT_HEALTHY_WINDOW_MS = 60_000L

// ---------------------------------------------------------- R1：环境不可用时降级（2026-10-05）

/**
 * 自适应「读不到环境」的降级阈值：连续这么多轮**相机确实出了帧、却一个可用人脸都没有**，
 * 就判定"环境不可用"，**临时**改按半自动（弹按钮）干活。
 *
 * ★ 判据为什么是"出帧但没人脸"，而不是"压根没出帧"：
 *   - **出帧但没人脸** = 相机是通的，只是画面里没有人脸（太暗 / 没对着镜头 / 脸被挡）
 *     ⇒ 这是**环境**问题，"点一下才转"对用户是净收益；
 *   - **压根没出帧** = 相机被抢 / 没开流 ⇒ 那是另一条链（`gaveUp` + 相机轮换），
 *     那边降级只会把故障盖住。
 *
 * 【取值】2 而不是 3：
 *   - 1 ⇒ 一次偶发（打了个哈欠、脸偏出画面）就降级，表现是"时灵时不灵"；
 *   - 3 ⇒ 暗光下要连转三次手机才等到按钮，用户早就认定"坏了"；
 *   - 2 ⇒ 第一次失败仍照原样重试，第二次失败才降级 —— 与 [RECENT_VOTES] 那条
 *     "宁可多看一眼再下结论"的取舍同向。
 */
const val R1_MISS_ROUNDS = 2

/**
 * 降级期间**放行一次真正的自适应探测**的间隔（ms）。
 *
 * ★★ 它存在的唯一理由：降级后引擎走半自动、**不再开相机** —— 而"环境恢复就自动切回"
 *   （用户 2026-10-05 拍板）必须有**感知恢复的手段**。本值就是那个手段：每隔这么久，
 *   允许**一次**触发走完整的自适应流程（开相机 → 找人脸）。找到 ⇒ 当场退出降级并转屏；
 *   找不到 ⇒ 重新计时。
 *
 * 【取值】20s 的两头：
 *   - 太短（< 5s）⇒ 暗光下几乎每次转动都白开一次相机，降级的省电意义就没了
 *     （半自动的全部优势就是不用相机）；
 *   - 太长（> 60s）⇒ 用户从暗处走到亮处后最坏要等一分钟才恢复，而这一分钟里
 *     自适应明明可用却按半自动跑，是**可见**的功能退化；
 *   - 20s ≈ "用户从昏暗走廊走到窗边"这个动作的量级。
 */
const val R1_PROBE_INTERVAL_MS = 20_000L

/**
 * 退出降级之后、多久内**不再重新进入**降级（ms）。
 *
 * ★ 这就是用户拍板那句"**带滞回 + 冷却**"里的**冷却**：防止"忽明忽暗"的场景里
 *   引擎在自适应与半自动之间来回切 —— 那种抖动的表现是"按钮一会儿有一会儿没有"，
 *   比稳定地待在任一档更让人困惑。
 * ★ 10s 够盖过"走过一根灯柱的阴影"这种瞬时变暗；再长就会让真正的暗光来得太晚
 *   （用户已经在暗处转了两次手机，却还没等到按钮）。
 */
const val R1_RECOVER_COOLDOWN_MS = 10_000L

/**
 * 熔断判据 —— **纯函数**，抽出来是为了能单测（与 [cn.dsr213.hyperplus.module.ModulePrefs.advanceBaseline]
 * 同一个理由：判据必须能脱离 SystemUI 进程被验证）。
 *
 * @param attempts 启动前从 `Settings.System` 读到的连续失败计数
 * @return true = 本次**不要**启动引擎，只上报 `phase=halted`
 */
fun bootBreakerTripped(attempts: Int): Boolean = attempts >= BOOT_BREAKER_THRESHOLD
