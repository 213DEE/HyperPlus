package cn.dsr213.hyperplus

import kotlin.math.abs
import kotlin.math.atan2
import kotlin.math.floor

/**
 * 「重力当尺子」—— 用重力把**人脸链路的符号位**自动钉死。纯逻辑、可离线单测。
 *
 * ============================================================================
 * 先说清一件事：重力**不参与**方向运算
 * ============================================================================
 *
 * 一度想写成一个"融合器"：`u = 重力扇区 + 人脸偏差扇区`。**这是错的，已放弃**，
 * 记在这里免得以后有人再想一遍：
 *
 * 设 `φ` = 设备相对世界正立方向**逆时针**转过的角度，
 *    `ψ` = 人头相对世界正立方向的倾斜角。
 * 于是「头顶相对设备顶边的顺时针夹角」`θrel = φ + ψ`，
 * 而屏幕要转的角度就是 `u = θrel / 90`（推导见下）。
 * 重力单独测出的是 `φ`；人脸单独测出的是 `θrel`。
 * ⇒ 两者相加 = `φ + (φ + ψ) = 2φ + ψ` —— **把设备自身的旋转算了两遍**。
 *
 * 反例（正常横屏）：手机逆时针 90°、头保持正立 ⇒ `φ=90`、`θrel=90`。
 * 正确 `u = 1`，而相加得到 `1 + 1 = 2`。**错得很明显，所以相加这条路是死的。**
 *
 * ============================================================================
 * 那"更精准"靠什么：靠在**符号位**上
 * ============================================================================
 *
 * `u = θrel / 90` 本身已经把方向算全了 —— 只要 `θrel` 测得对。
 * 唯一不确定的是**相机链路的符号**：ML Kit 的 `headEulerAngleZ` 与 `θrel` 之间
 * 隔着「前置镜像 / 左右眼定义 / 传感器朝向」三层，可能同号也可能反号，
 * 等价于一个未知的 `sign = ±1`：
 *
 * ```
 *   sign = +1 ⇒ u = sectorOf( θrel)      ← 正确
 *   sign = -1 ⇒ u = sectorOf(-θrel)      ← 0→0、1→3、2→2、3→1：**恰好只把两个横屏对调**
 * ```
 *
 * ⇒ **`sign` 取反在竖屏（0/2）上完全看不出来，只在横屏上表现为"方向反过来"** ——
 *    这正是用户反复报的「横屏的时候有概率反过来」「转动方向越来越反」。
 *
 * ★ 而真机上 `calib_sign=1 / calib_offset=0.0` **正好等于代码默认值**：
 *   说明这个符号位从未被真正钉死过（`OrientationDecider` 的注释自己也写着
 *   "理论应为 -1 …… 实测却支撑 +1 …… 两者冲突，❓待标定确定"）。
 *
 * ============================================================================
 * 重力怎么当尺子（[verdict]）
 * ============================================================================
 *
 * 日常使用中**人头是朝着世界正立的**（`ψ ≈ 0`），此时 `θrel ≈ φ` ——
 * 也就是"人脸链路算出的扇区"应当**等于重力扇区**。于是：
 *
 * ```
 *   实测扇区 == 重力扇区        ⇒ 当前 sign 是对的          （SAME）
 *   实测扇区 == 镜像(重力扇区)  ⇒ 当前 sign 反了，应翻转     （FLIPPED）
 *   两者都不等                  ⇒ 这一帧分辨不了（头真的歪着）⇒ 不记票（AMBIGUOUS）
 * ```
 *
 * ⚠️ **只有重力扇区 ∈ {1, 3} 的帧才算数**：`mirror(0)=0`、`mirror(2)=2`，
 *   竖屏/倒置时两种 sign 给出同一个结果，记进去只会稀释真正的信号。
 *
 * ★ 这条判据是**自证**的：它不需要我猜哪个符号对，也不需要用户点两次校准；
 *   它只看"哪一种解释更能解释实测数据"。累计足够多的分辨帧后取多数即可。
 *
 * ★ 顺带解决一个遗留问题：`OrientationDecider` 那份"两步点按校准"只要用户点歪一次
 *   就把符号钉错，而且界面照样显示"已校准"。改用本判据后，"已校准"才是有证据的。
 */
object OrientationFusion {

    /**
     * 加速度计读数 → **屏幕方向扇区**（0/1/2/3，语义与 `Surface.ROTATION_*` 一致）。
     *
     * ## 推导链（全部由物理常量与官方语义推出，**没有任何拟合参数**）
     *
     * 1) 设备坐标系：`x` = 右、`y` = 上（朝顶边）、`z` = 屏幕外法线（朝用户）。
     * 2) 静止时加速度计测的是**比力** = `a − g`；静止即 `a = 0` ⇒ 它读出的方向就是
     *    **世界的「上」在设备坐标里的表示**。（实证常识：手机平放面朝上读 `z ≈ +9.81`。）
     * 3) 设 `φ` = 设备相对自然方向**逆时针**转过的角度（观察者视角）。世界「上」是固定的，
     *    而设备坐标跟着转了 `φ` ⇒ 它在设备坐标里被**反向**表示：
     *    ```
     *      (ax, ay) = g · ( sin φ , cos φ )
     *    ```
     *    逐点自检：`φ=0` → `(0, +g)` ✓；`φ=90°`（顶边朝左）→ `(+g, 0)` ✓；
     *              `φ=180°` → `(0, −g)` ✓。
     *    ⇒ **`φ = atan2(ax, ay)`**。
     * 4) `Surface.ROTATION_*` 的编号就是 `φ/90`（见下表的真机实证），故扇区 = 量化后的 `φ`。
     *
     * ## 四个姿势逐点验算（单测 [OrientationFusionTest] 据此钉死）
     *
     * | 设备物理姿态 | 加速度计读数 | `atan2(ax, ay)` | 扇区 | 项目实测的对应关系 |
     * |---|---|---|---|---|
     * | 竖屏正立（自然方向） | (0, +g, 0) | 0° | 0 | `ROTATION_0` ✓ |
     * | 逆时针转 90°（顶边朝左） | (+g, 0, 0) | +90° | **1** | `ROTATION_90` ✓ |
     * | 倒置 180° | (0, −g, 0) | 180° | 2 | `ROTATION_180` ✓ |
     * | 顺时针转 90°（顶边朝右） | (−g, 0, 0) | −90° | **3** | `ROTATION_270` ✓ |
     *
     * ⚠️ **符号极易推错，本函数已被真机实证纠正过一次**：初版写的是 `atan2(-ax, ay)`，
     *   纸面上"看着也自洽"，但 2026-09-25 用平台自己的朝向码一比就露馅了 ——
     *   竖屏能对上（0/2 是镜像不变点），**两个横屏整体对调**：
     *   ```
     *   重力交叉校验：TYPE_27=1  重力扇区=3（差2格）  ax=8.16 ay=0.35
     *   重力交叉校验：TYPE_27=3  重力扇区=1（差2格）  ax=-8.43 ay=-0.68
     *   重力交叉校验：TYPE_27=0  重力扇区=0（一致）   ax=-1.37 ay=8.73
     *   ```
     *   改成 `atan2(ax, ay)` 后 9 组采样全部一致（见单测的 [matchesPlatformType27Samples]）。
     *   ⇒ **再改这个符号之前，先看日志里 [crossCheck] 的 `TYPE_27 码 vs 重力扇区`，
     *     不要靠纸面推导，也不要凑参数。**
     */
    fun gravitySector(ax: Float, ay: Float): Int {
        val roll = Math.toDegrees(atan2(ax.toDouble(), ay.toDouble())).toFloat()
        return sectorOf(roll)
    }

    /**
     * 带「可信度闸门」的版本：手机**完全平放**时重力几乎全落在 z 轴，平面分量只剩噪声，
     * 此时算出来的 roll 是随机的 ⇒ 返回 `null` 表示"这一帧重力给不出方向"。
     *
     * @param minPlanarG 平面分量阈值（单位 = m/s²）。取 `1.5f` 而不是 2~3：
     *   手机斜拿着看视频（俯仰 60°~70°）时平面分量只有 `g*cos(70°) ≈ 3.4`，
     *   阈值定太高会把**正常使用姿势**误判成平放。
     */
    fun gravitySectorOrNull(ax: Float, ay: Float, minPlanarG: Float): Int? {
        if (abs(ax) < minPlanarG && abs(ay) < minPlanarG) return null
        return gravitySector(ax, ay)
    }

    /** 归一到 `[0, 360)` */
    fun norm360(deg: Float): Float {
        var n = deg % 360f
        if (n < 0f) n += 360f
        return n
    }

    /**
     * 量化到**最近的** 90° 扇区（与 `OrientationDecider.sectorOf` 同解，
     * 这里独立实现一份是为了让本类能脱离 Android/Decider 单独单测）。
     */
    fun sectorOf(deg: Float): Int = (floor((norm360(deg) + 45f) / 90f).toInt()) % 4

    /**
     * 「符号位取反」在扇区编号上的表现：**1↔3 对调，0/2 保持不变**（= 关于竖轴镜像）。
     *
     * ★ 这就是 `sign` 取反的全部后果 —— 也解释了为什么这个 bug 只在横屏上暴露。
     */
    fun mirror(sector: Int): Int = (((4 - sector) % 4) + 4) % 4

    /** [gauge] 的两种结论 */
    enum class Gauge {
        /** 照常写 —— 包括"朝上"（与重力一致）与"朝左／朝右"（相对重力差 90°，是合法姿势） */
        OK,

        /**
         * ★★★ 目标是「**朝下**」—— 内容相对重力整整差了 180°，**任何**合法握姿都不需要它，
         * 所以它只可能是判错 ⇒ **改写成重力给的那个值**（内容立刻回正）。
         */
        UPSIDE_DOWN,
    }

    /**
     * ★★★ **「朝下」是哪个值 —— 拿重力算，不是写死的 `2`。**
     *
     * 用户 2026-10-03 的两句话（第二句是**纠正**我第一版做成"硬禁 2"）：
     * > 「利用重力加多一重判断，画面永远只会朝上、朝左、朝右，**永远不可能朝下**，
     * >   因为人会站着、坐着、躺着玩手机，但**不可能倒立玩手机**」
     * > 「**永远不朝下 不等于 `user_rotation ≠ 2`**，要利用重力判断，**手机本身是可以翻转的**」
     *
     * ## 为什么不能硬禁 `2`
     * `user_rotation` 是**相对面板自然方向**的渲染旋转，`2` 本身没有任何罪 ——
     * 手机**真的**被翻过来（顶边朝下）时，正需要 `2` 才能让内容对用户是正的。
     * 有罪的只有一件事：**写出去的值让内容相对重力差了 180°**（用户看到的就是倒过来的画面）。
     *
     * ## 判据：相对重力差 180° ⇒ 朝下
     * ```
     *   target == (gravity + 2) % 4      ⇒  朝下（upside down）
     * ```
     * 逐格验算（这就是为什么它**不能**用 [mirror]：`mirror(0)=0`、`mirror(2)=2`，
     * 竖屏那两格会被漏掉 —— 而竖屏的 0↔2 恰恰也是 180°）：
     * | 重力 | 朝下的值 | 说明 |
     * |---|---|---|
     * | 0（竖持正立） | 2 | 手机没翻却写 2 ⇒ 画面倒 |
     * | 1（横持） | 3 | 写反的那个横屏 ⇒ 画面倒 |
     * | 2（**手机被翻过来**） | 0 | ⚠️ 此时 `2` 是**正确**的，写 0 才叫倒 |
     * | 3（横持） | 1 | 同上 |
     *
     * ## 差 90° 的一律放行（这一点同样是用户定的）
     * 用户只禁了"朝下"，**"朝左／朝右"（相对重力差 90°）是合法结果**，别去拦 ——
     * 因为**躺着玩**就是典型情形：人躺着时重力说竖屏、而脸是横的，
     * 此时人脸链路给出的横屏值**才是对的**，它天然就与重力差 90°。
     * ⇒ 拦掉 90° 会让"躺着玩"直接不转（第一版我就犯了这个错，已改）。
     *
     * ⚠️ 重力这一路不可用时（手机平放、读数过期、触发层没起来）**一律放行**：
     *   没有尺子就判不出哪一格是"朝下"，硬拦只会把"没有重力的场景"整个变成不转。
     *
     * ⚠️ 上面两条判据**互斥**（`g == (g+2)%4` 无解）⇒ **顺序在逻辑上无关**，
     *   把"一致"放前面纯粹为了好读（先排除最常见的那支）。
     *   ⛔ **别再写"顺序不能换，否则会把 `gravity==2 && target==2` 误判成朝下"** ——
     *      **那句话是错的**（10-03 我在 KDoc／铁律／说明文档里同时写错，已订正）：
     *      此时 `upsideDownOf(2) = 0`，而 `target = 2`，`2 == 0` 不成立，**根本进不了那一支**。
     */
    fun gauge(target: Int, gravity: Int): Gauge = when {
        target !in 0..3 || gravity !in 0..3 -> Gauge.OK
        target == gravity -> Gauge.OK
        target == upsideDownOf(gravity) -> Gauge.UPSIDE_DOWN
        // 其余都是相对重力差 90°（朝左／朝右）—— 躺着手持等合法姿势，放行
        else -> Gauge.OK
    }

    /**
     * 相对 [gravitySector] **差 180°** 的那个方向 —— 也就是「**朝下**」。
     *
     * ⛔ 别用 [mirror] 代替它：`mirror` 是**符号位**算子（1↔3 对调、0/2 不动），
     *   在竖屏上它与"差 180°"不是一回事（`mirror(0)=0`，而朝下的值是 2）。
     *   二者只在横屏上恰好重合，这正是最容易混淆的地方。
     */
    fun upsideDownOf(gravitySector: Int): Int = (gravitySector + 2) % 4

    /** [verdict] 的三种结论 */
    enum class Verdict {
        /** 实测扇区 == 重力扇区 ⇒ 当前符号位是对的 */
        SAME,

        /** 实测扇区 == 镜像(重力扇区) ⇒ 当前符号位反了 */
        FLIPPED,

        /** 这一帧分辨不了（头真的歪着 / 重力在竖屏象限 / 缺一路数据）⇒ 不记票 */
        AMBIGUOUS,
    }

    /**
     * 拿重力当尺子，判"当前符号位对不对"。**本类的核心判据。**
     *
     * @param measuredSector 人脸链路算出的扇区（0..3；负数视为无效）
     * @param gravitySector  重力算出的扇区（0..3；负数 = 这一路不可用）
     *
     * ★ 为什么 `gravitySector ∈ {0,2}` 一律返回 [Verdict.AMBIGUOUS]：
     *   `mirror(0)=0`、`mirror(2)=2`，此时两种符号位给出**完全相同**的结果，
     *   该帧对"哪个符号对"零信息量。把它记成 SAME 会让大量竖屏帧
     *   把真正的 FLIPPED 信号稀释掉 ⇒ 永远发现不了符号位错。
     */
    fun verdict(measuredSector: Int, gravitySector: Int): Verdict = when {
        measuredSector !in 0..3 -> Verdict.AMBIGUOUS
        gravitySector !in 0..3 -> Verdict.AMBIGUOUS
        gravitySector == 0 || gravitySector == 2 -> Verdict.AMBIGUOUS
        measuredSector == gravitySector -> Verdict.SAME
        measuredSector == mirror(gravitySector) -> Verdict.FLIPPED
        else -> Verdict.AMBIGUOUS
    }

    /**
     * 累计票数 → 是否该翻转符号位。
     *
     * 判据刻意"苛刻"：分辨帧要够多，且反号证据要有明显优势（3 倍）。
     * 符号位一旦定错是**全局性**的错（整片横屏反向），宁可多等几百帧，
     * 也不能被一次"头歪着看手机"的偶然采样带偏。
     */
    fun shouldFlip(same: Int, flipped: Int, minSamples: Int): Boolean =
        flipped >= minSamples && flipped >= 3 * same

    /**
     * 是否已经**有证据地**确认当前符号位。用于把界面上那句"已校准"从"点过按钮"
     * 升级为"被数据验证过"—— 语义瑕疵的修补。
     */
    fun signConfirmed(same: Int, flipped: Int, minSamples: Int): Boolean =
        same >= minSamples && same >= 3 * flipped

    /**
     * 与 [cn.dsr213.hyperplus.trigger.DeviceOrientationTrigger] 的 `TYPE_27` 朝向码做
     * 交叉校验，只用于日志。
     *
     * @return 形如 `一致` / `差-1格` 的短串；`code < 0`（还没收到过）时返回 `—`。
     */
    fun crossCheck(gravitySector: Int, type27Code: Int): String {
        if (type27Code < 0) return "—"
        var d = (gravitySector - type27Code) % 4
        if (d > 1) d -= 4
        if (d < -1) d += 4
        return if (d == 0) "一致" else "差${d}格"
    }
}
