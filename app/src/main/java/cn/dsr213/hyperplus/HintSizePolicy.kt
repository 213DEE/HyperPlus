package cn.dsr213.hyperplus

/**
 * 旋转按钮的**尺寸策略**：给定"当前屏的最小宽度（dp）"，算出按钮该多大。
 *
 * ============================ 为什么要单独一个文件 ============================
 * 这是纯算术，但**只有装到机器上才看得出对错**，而且错法极隐蔽 —— 2026-09-28 出过一次：
 * 密度从 440dpi(2.75x) 误写成 4.088 ⇒ 比例算成 0.132 ⇒ 内屏 `608 × 0.132 = 80dp`、
 * 外屏 `425 × 0.132 = 56dp`，**两块屏双双撞上"上限"被夹到同一个值** —— 也就是"按屏宽
 * 自适应"实际失效，外屏上按钮占屏宽 12.7%（内屏只有 8.9%），肉眼就是"外屏的大了一圈"。
 * 代码里每个数字看着都对，只有把两块屏**同时**代入才能发现。
 *
 * ⇒ 抽成不依赖任何 Android 类的纯函数（能进 JVM 单测），拿真机实测的两档宽度当输入，
 *   把"内屏多少、外屏多少"钉死在 `HintSizePolicyTest` 里。改常量时测试会立刻告诉你
 *   两块屏分别变成了多大 —— 这正是上面那次错误缺的反馈。
 *
 * ★ 量法唯一来源：屏宽由 [DisplaySize] 给出（`min(宽,高)`，**旋转不变量**）——
 *   横屏时按钮不会因为"屏幕变宽了"而跟着变大。详见 `RotateHintOverlay.hintSize()`。
 */
internal object HintSizePolicy {

    /**
     * 参考屏宽：**本机内屏的最小宽度**（1672px ÷ 密度 2.75 = **608dp**）。
     *
     * ★ 它只是一根"基准刻度"，不是"内屏恒为 608dp"的假设。真正的算式是
     *   `可见圆 = 当前屏最小宽度 × [VISUAL_W_RATIO]`，再夹到 [VISUAL_DP_MIN]~[VISUAL_DP_MAX]。
     *   需要这根刻度的理由：把"用户认可的某个尺寸"换算成一个**比例** ——
     *   比例才是跨屏幕尺寸可比的东西（绝对 dp 不是）。
     */
    const val REF_SCREEN_WIDTH_DP = 608

    /**
     * 可见圆的**上限**，也是**内屏的目标尺寸**：**62dp**。
     *
     * ★ 来历：2026-09-29 用户报「按钮有点小」，并明确要求
     *   「把外屏按钮加大到现在内屏的尺寸，然后把内屏按钮也加大一点」。
     *   - "现在内屏的尺寸" = 上一版的 54dp（2026-09-28 用户报"按键太大了"从 76dp 降下来的那个值）；
     *   - "内屏也加大一点" = 从 54 提到 **62dp**（+8dp ≈ +15%，肉眼可辨但没回到"占一块地方"）。
     *
     * ⚠️ 为什么不能更小：它是**触摸目标**，48dp 是 Material / 无障碍的推荐下限。
     *   62dp 留了充足余量（悬浮按钮还得考虑单手、边走边点）。
     */
    const val VISUAL_DP_MAX = 62

    /**
     * 可见圆的**下限**，也是**外屏的目标尺寸**：**54dp**。
     *
     * ★ 它**不是随手定的数**，而是用户这条要求的落点：外屏要等于"上一版内屏的尺寸"
     *   （54dp），两块屏的按钮在物理尺寸上就一样大了。
     *
     * ⚠️ 注意这个下限**比比例算出来的值高出不少** ——
     *   外屏宽 425dp，`425 × [VISUAL_W_RATIO](= 62/608) ≈ 43.3dp` ⇒ 被夹到 54dp。
     *   也就是说：**外屏的尺寸现在是"夹出来的固定值"，不再随屏宽变化**。
     *   这是用户明确要的结果（外屏就得跟内屏一样大），不是副作用。
     *   副作用只有一个方向：**以后若把 [VISUAL_DP_MAX] 往下调得比 54 低，
     *   两块屏会一起被夹成同一个值**（外屏恒等于下限、内屏撞上限），
     *   自适应又变成失效状态 —— 改上限时务必跑 `HintSizePolicyTest` 看一眼两块屏。
     *
     * ⚠️ 历史提醒：54dp 在外屏上占屏宽 **12.7%**（内屏 62dp 占 10.2%），
     *   即外屏上按钮"看着比内屏大一圈"。2026-09-28 曾因这个观感把它压到 38dp，
     *   但 2026-09-29 用户的反馈是"外屏按钮太小" —— 理由很实在：**外屏物理尺寸小、
     *   手指还是同一根手指**，按比例缩下去反而难点中。⇒ 以用户现场观感为准，取 54dp。
     */
    const val VISUAL_DP_MIN = 54

    /**
     * 可见圆占屏宽的比例 = `62 / 608` ≈ **0.10197**。
     *
     * ★ 为什么用比例而不是绝对 dp：用户的原话是「考虑内屏和外屏的**不同尺寸**」。
     *   同一颗 54dp 的按钮，在内屏占 8.9%、在外屏占 12.7%（两块屏密度相同，都是 440dpi）
     *   —— 绝对 dp 做不到"看起来一样大"，**占屏宽的比例相等**才做得到。
     *
     * ⚠️ 写成 `val` 而不是 `const val`：`Int.toFloat()` 不是编译期常量表达式，
     *   写成 const 编译不过。代价只是多一次静态初始化。
     */
    val VISUAL_W_RATIO = VISUAL_DP_MAX.toFloat() / REF_SCREEN_WIDTH_DP

    /**
     * 触摸区下限：**48dp**（Material / 无障碍推荐值）。
     *
     * ★ 这是"视觉尺寸"与"可点性"分家的那一条：**窗口**取 `max(可见圆, 48dp)`，
     *   可见圆在窗口里**居中**画，外面那圈是透明触摸余量（见 `RotateHintOverlay.HintSize`）。
     *
     * ⚠️ 当前参数下这条**用不上**：可见圆最小也有 54dp > 48dp ⇒ 窗口恒等于可见圆、
     *   `contentScale` 恒为 1（两块屏都是）。保留它是因为它是**安全网** ——
     *   一旦将来把 [VISUAL_DP_MIN] 调到 48 以下（比如给某种小屏设备），
     *   可点性会自动被这条兜住，不需要重新想一遍。
     */
    const val TOUCH_DP_MIN = 48

    /**
     * 按钮"可见圆"的直径（dp）—— 由当前屏最小宽度算出来，再夹进上下限。
     *
     * 本机两档实测结果（[HintSizePolicyTest] 钉住）：
     * | 屏 | 最小宽度 | 比例算得 | 夹完 |
     * |---|---|---|---|
     * | 内屏 | 608dp | 62.0dp | **62dp**（撞上限） |
     * | 外屏 | 425dp | 43.3dp | **54dp**（撞下限） |
     */
    fun visualDp(smallestWidthDp: Int): Float =
        (smallestWidthDp * VISUAL_W_RATIO)
            .coerceIn(VISUAL_DP_MIN.toFloat(), VISUAL_DP_MAX.toFloat())

    /**
     * **窗口**边长（dp）= 触摸区边长 = `max(可见圆, 48dp)`。
     *
     * 当前参数下恒等于 [visualDp]（见 [TOUCH_DP_MIN] 的说明），保留这个函数是为了让
     * "视觉"与"可点性"这两件事在代码里**始终是两个名字**，不会有人顺手合并掉。
     */
    fun viewDp(visualDp: Float): Float = maxOf(visualDp, TOUCH_DP_MIN.toFloat())
}
