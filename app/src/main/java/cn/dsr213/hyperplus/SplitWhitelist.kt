package cn.dsr213.hyperplus

/**
 * ★★★ **分屏名单** —— 「哪些应用折一下也不加分屏」的唯一判据（2026-10-05 新增）。
 *
 * ============================ 用户要的是什么 ============================
 * 用户 2026-10-05 原话：「**分屏增强也添加应用列表，把市面上常见的游戏包名添加进默认列表**」。
 *
 * 语义（**当天拍板**）：「**名单内不触发分屏**」——
 * 命中名单的应用在前台时，用户折一下手机**不**会把它挤成半屏。
 * 默认清单 = **市面上常见的游戏**。
 *
 * ============================ 为什么游戏要默认进这份名单 ============================
 * 三个都不轻的理由：
 * ① **游戏在内屏是全屏独占的**：把正在打的游戏挤成半屏，几乎不会是用户那一刻想要的
 *    （他要的是"再开一个应用陪玩"这种场景属于少数，而且他有别的入口：三指滑 / 拖到图标）；
 * ② **折手机这个动作在游戏里太容易误触**：横屏持握、手腕翻转，铰链必然动 ——
 *    不挡的话，"手抖一下屏幕裂成两半"会变成高频困扰；
 * ③ **分屏代价对游戏最高**：分屏 = 两个 stage 同时合成，GPU 开销接近翻倍，
 *    而游戏本来就是最吃 GPU 的场景（与 [AppWhitelist.DEFAULT_GAMES] 那段"断触"的
 *    成因是**同一件事的两面**：都是"别在游戏最需要性能的时候给它加活"）。
 *
 * ============================ 它为什么**不**复用旋转那份名单（用户明确拍板）============================
 * 用户当天选了「**各自独立一份**」。理由（写下来免得以后有人想合并）：
 *
 * | | 旋转名单（[AppWhitelist]） | 分屏名单（本对象） |
 * |---|---|---|
 * | 命中含义 | 那个应用**转屏**本应用不干涉 | 那个应用**折不折** |
 * | 默认清单 | 常见游戏 **+ 长视频/播放器** | **只有游戏** |
 * | 典型反例 | 用户想让某个 MMO 自己管朝向 | 用户想让那个 MMO 能折出分屏 |
 *
 * ⚠️ **两个维度的默认值刻意不同**：长视频**不进**分屏名单。
 *   理由是分屏对视频是**有意义**的（边看边刷），而对游戏几乎只有代价；
 *   而且视频应用折一下会**停在播放页**，用户的预期比较模糊 —— 让他自己决定更合适。
 *   ⛔ 别因为"两份清单长得像"就把视频那批一起抄过来。
 *
 * ============================ 与旋转名单共用的部分 ============================
 * ① **编码格式**：直接复用 [AppWhitelist.encode] / [AppWhitelist.decode]
 *    —— 同一个"每行一个包名"约定，⛔ 不另写一份（两份实现迟早会分叉）。
 * ② **集合运算法**：`DEFAULT + added − removed`（见 [resolve]），
 *    以及"不检查包是否已安装"那条判断（理由逐字同 [AppWhitelist] 类注释）。
 * ③ **游戏包名清单**：直接**引用** [AppWhitelist.DEFAULT_GAMES]，⛔ 不复制一份字面量。
 *    ⚠️ 这里引用的是**同一个集合对象**，所以给旋转名单加一个游戏时，分屏名单自动跟上 ——
 *      那正是我们想要的（"市面上常见的游戏"对两个功能是同一个集合，没有分家的理由）。
 */
internal object SplitWhitelist {

    /**
     * 分屏默认名单：**游戏**。
     *
     * ★ 直接引用 [AppWhitelist.DEFAULT_GAMES]（理由见类注释第 ③ 条）——
     *   本对象**刻意不写第二份包名清单**：两处各写一份的后果是"加了一个游戏只改对一处"，
     *   而且**不报错**。
     * ⚠️ 顺带拿到那条纪律：这份清单是**尽力而为**的（包名以官方商店为准），
     *   而且**写错无害**（不存在的包名永远不会成为前台应用）⇒ 判据是"宁多勿少"。
     */
    val DEFAULT_GAMES: Set<String> = AppWhitelist.DEFAULT_GAMES

    /**
     * 出厂默认集合。★ 刻意**只是一个别名**（不写 `= DEFAULT_GAMES` 之外的任何运算）——
     * 留着这个具名常量是为了让将来"分屏名单要补一类别的默认项"时有一个**唯一落点**。
     * ⛔ 别为了"看起来简洁"把引用它的地方直接改成 `DEFAULT_GAMES`：
     *   那样这个落点就没了，下一次加默认类别要满仓库找引用点。
     */
    val DEFAULT_PACKAGES: Set<String> = DEFAULT_GAMES

    /**
     * 算出**生效**分屏名单。
     *
     * 算式与 [AppWhitelist.resolve] 逐字相同（同一套"默认 ∪ 加集 − 减集"）。
     *
     * @param added   用户手动加进来的包
     * @param removed 用户手动移出的包。**必须是一份独立存下来的减集**
     *   （理由见 [PrefsBridge.SPLIT_WHITELIST_REMOVE]）：只删加集的话，
     *   [DEFAULT_PACKAGES] 里的游戏会在下一次现算时被默认值顶回来。
     */
    fun resolve(added: Set<String>, removed: Set<String>): Set<String> =
        DEFAULT_PACKAGES + added - removed

    /**
     * 这个包是不是出厂默认就在分屏名单里。界面用它决定开关的**初始状态**。
     */
    fun isDefault(pkg: String): Boolean = pkg in DEFAULT_PACKAGES
}
